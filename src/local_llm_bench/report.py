"""Turn results files into the table the README links to.

Every number is derived from the raw measurements in results/*.jsonl: the median over the
measured repetitions, warmups left out. Nothing is corrected or filled in by hand. If a
tier was run more than once, only its newest run counts.
"""

from __future__ import annotations

import statistics
from collections.abc import Iterable
from dataclasses import dataclass
from pathlib import Path

from local_llm_bench.config import BenchConfig
from local_llm_bench.environment import Environment
from local_llm_bench.results import Measurement

NS_PER_MS = 1_000_000
BYTES_PER_GIB = 1024**3

# Text that identifies a known failure in an error message, and what it means.
KNOWN_FAILURES = {
    "insufficient memory": "not enough memory to load",
    "Server disconnected": "server died mid-request",
}


@dataclass(frozen=True)
class Run:
    """One results file and the .env.json written next to it."""

    path: Path
    env: Environment
    measurements: list[Measurement]


@dataclass(frozen=True)
class Summary:
    """One model with one prompt regime on one tier: a row of the results table."""

    tier_id: str
    model_id: str
    regime_id: str
    measured: int  # repetitions that produced numbers
    planned: int
    ttft_ms: float | None
    prompt_tps: float | None
    gen_tps: float | None
    loaded_gib: float | None
    gpu_share: float | None  # share of the loaded bytes held in VRAM, 0 to 1
    failure: str | None


def load_runs(results_dir: Path) -> dict[str, Run]:
    """The newest run of each tier, keyed by tier id."""
    runs: dict[str, Run] = {}
    for path in sorted(results_dir.glob("*.jsonl")):
        env_text = path.with_suffix(".env.json").read_text(encoding="utf-8")
        env = Environment.model_validate_json(env_text)
        newest = runs.get(env.tier_id)
        if newest is None or env.started_at > newest.env.started_at:
            lines = path.read_text(encoding="utf-8").splitlines()
            measurements = [Measurement.model_validate_json(line) for line in lines if line]
            runs[env.tier_id] = Run(path, env, measurements)
    return runs


def summarize(config: BenchConfig, run: Run) -> list[Summary]:
    """One row per model and regime, in config order, including pairs that never ran."""
    return [
        _summary(run, model.id, regime.id, config.run.repetitions)
        for model in config.models
        for regime in config.regimes
    ]


def _summary(run: Run, model_id: str, regime_id: str, planned: int) -> Summary:
    group = [m for m in run.measurements if m.model_id == model_id and m.regime_id == regime_id]
    measured = [m for m in group if not m.warmup and m.error is None]
    errors = [m.error for m in group if m.error is not None]
    if errors:
        failure: str | None = describe_failure(errors[-1])
    elif not group:
        failure = "not run"
    else:
        failure = None

    ttft_ns = _median(m.ttft_ns for m in measured)
    loaded_bytes = _median(m.loaded_bytes for m in measured)
    return Summary(
        tier_id=run.env.tier_id,
        model_id=model_id,
        regime_id=regime_id,
        measured=len(measured),
        planned=planned,
        ttft_ms=None if ttft_ns is None else ttft_ns / NS_PER_MS,
        prompt_tps=_median(m.prompt_tps for m in measured),
        gen_tps=_median(m.gen_tps for m in measured),
        loaded_gib=None if loaded_bytes is None else loaded_bytes / BYTES_PER_GIB,
        gpu_share=_median(_gpu_share(m) for m in measured),
        failure=failure,
    )


def describe_failure(error: str) -> str:
    for marker, meaning in KNOWN_FAILURES.items():
        if marker in error:
            return meaning
    return error if len(error) <= 60 else error[:57] + "..."


def _gpu_share(m: Measurement) -> float | None:
    if not m.loaded_bytes or m.loaded_vram_bytes is None:
        return None
    return m.loaded_vram_bytes / m.loaded_bytes


def _median(values: Iterable[float | None]) -> float | None:
    present = [v for v in values if v is not None]
    return statistics.median(present) if present else None


def markdown(config: BenchConfig, runs: dict[str, Run], summaries: list[Summary]) -> str:
    lines = [
        "# Results",
        "",
        "Generated by `llm-bench report` from the files in `results/`. Do not edit by hand:",
        "re-run the command.",
        "",
        "Every number is the median over the measured repetitions; the warmup request is left",
        "out. TTFT is measured by the client, from sending the request to the first streamed",
        "token. Sizes are GiB (1024³ bytes). GPU is the share of Ollama's loaded memory held in",
        "VRAM: below 100 % on a GPU tier means the model was split with system RAM.",
        "",
        "![Generation speed against model size](gen-speed.png)",
        "",
        "![Memory each model needs against what each tier has](memory-fit.png)",
    ]
    for tier in config.tiers:
        if tier.id not in runs:
            continue
        run = runs[tier.id]
        lines += ["", f"## {tier.id} · {tier.name}", "", _machine(run), ""]
        lines += [
            "| Model | Regime | Measured | TTFT ms | Prompt tok/s | Gen tok/s | Loaded GiB "
            "| GPU | Failure |",
            "|---|---|---:|---:|---:|---:|---:|---:|---|",
        ]
        lines += [_table_row(s) for s in summaries if s.tier_id == tier.id]
    return "\n".join(lines) + "\n"


def _machine(run: Run) -> str:
    env = run.env
    ram = "RAM unknown"
    if env.memory_bytes is not None:
        ram = f"{env.memory_bytes / BYTES_PER_GIB:.1f} GiB RAM"
    parts = [
        env.cpu or "unknown CPU",
        env.gpu or "no NVIDIA GPU",
        ram,
        env.system,
        f"Ollama {env.ollama_version or 'unknown'}",
        f"harness {(env.git_commit or 'unknown')[:7]}",
        f"started {env.started_at:%Y-%m-%d %H:%M} UTC",
        f"`results/{run.path.name}`",
    ]
    if env.git_dirty:
        parts.append("**uncommitted changes: matches no commit**")
    return " · ".join(parts)


def _table_row(s: Summary) -> str:
    cells = [
        s.model_id,
        s.regime_id,
        f"{s.measured}/{s.planned}",
        _number(s.ttft_ms),
        _number(s.prompt_tps),
        _number(s.gen_tps),
        "–" if s.loaded_gib is None else f"{s.loaded_gib:.2f}",
        "–" if s.gpu_share is None else f"{s.gpu_share:.0%}",
        (s.failure or "").replace("|", "\\|"),
    ]
    return "| " + " | ".join(cells) + " |"


def _number(value: float | None) -> str:
    """About three significant figures: run-to-run noise is larger than any further digit."""
    if value is None:
        return "–"
    if value >= 100:
        return f"{value:,.0f}"
    return f"{value:.1f}" if value >= 10 else f"{value:.2f}"
